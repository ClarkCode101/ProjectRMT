// Bundles the Last Card rules into ONE file for the Edge Function `cards-game` (PROJECT_PLAN.md §15 step 2), so the
// live game on the server plays by exactly the same rules (and tests) as the solo game in the app.
//
//   npm run build:cards-rules
//     → supabase/functions/cards-game/rules.js        (the bundle the function imports; in git)
//     → deploy/cards-game-for-dashboard.ts             (index.ts + the rules in ONE file, to paste into the Supabase
//                                                        Dashboard editor when deploying; not in git)
//
// Run it after changing any file in RULE_SOURCES (or index.ts). The first line of rules.js holds a fingerprint of
// those files; scripts/build-cards-rules.test.ts fails if they changed but rules.js wasn't built again.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { build } from 'rolldown'

export const RULE_SOURCES = [
  'src/lib/cards.ts',
  'src/lib/cardsLive.ts',
  'src/lib/cardsDev.ts',
  'src/lib/cardsLiveDev.ts',
  'src/lib/cardsServer.ts',
  'src/lib/board.ts',
  'src/lib/quiz.ts',
]
const ENTRY = 'src/lib/cardsServer.ts'
const OUT = 'supabase/functions/cards-game/rules.js'
const FUNCTION = 'supabase/functions/cards-game/index.ts'
const DASHBOARD = 'deploy/cards-game-for-dashboard.ts'

/** Same text on Windows and elsewhere (git may turn line endings into CRLF on checkout). */
export function rulesFingerprint(read: (path: string) => string = (p) => readFileSync(p, 'utf8')): string {
  const hash = createHash('sha256')
  for (const path of RULE_SOURCES) hash.update(`${path}\n${read(path).replace(/\r\n/g, '\n')}\n`)
  return hash.digest('hex').slice(0, 16)
}

/** index.ts with the rules pasted in place of `import * as rules from './rules.js'`. */
function dashboardFile(rulesCode: string): string {
  const index = readFileSync(FUNCTION, 'utf8').replace(/\r\n/g, '\n')
  const importLine = "import * as rules from './rules.js'\n"
  if (!index.includes(importLine)) throw new Error(`${FUNCTION} no longer has: ${importLine}`)
  const exportLine = rulesCode.match(/\nexport \{([^}]*)\};\s*$/)
  if (!exportLine) throw new Error('The rules bundle has no export line at the end.')
  const names = exportLine[1].split(',').map((s) => s.trim()).filter(Boolean)
  const [head, tail] = index.split(importLine)
  return [
    '// cards-game, ONE FILE for pasting into the Supabase Dashboard editor (Edge Functions → cards-game).',
    '// Made by `npm run build:cards-rules` from supabase/functions/cards-game/index.ts + rules.js. Don\'t edit this copy.',
    '',
    head.trimEnd(),
    '',
    '// ===== The Last Card rules (rules.js) =====',
    rulesCode.slice(0, exportLine.index).trimEnd(),
    `const rules = { ${names.join(', ')} }`,
    '// ===== The function =====',
    '',
    tail.trimStart(),
  ].join('\n')
}

async function main() {
  const result = await build({ input: ENTRY, write: false, output: { format: 'esm' } })
  const code = result.output[0].code
  const header = [
    `// rules-fingerprint: ${rulesFingerprint()}`,
    `// GENERATED by scripts/build-cards-rules.ts from ${ENTRY} (cards.ts, cardsLive.ts, cardsDev.ts, cardsLiveDev.ts, board.ts, quiz.ts).`,
    '// Do not edit by hand: change those files, then run `npm run build:cards-rules`.',
    '',
  ].join('\n')
  writeFileSync(OUT, header + code)
  mkdirSync('deploy', { recursive: true })
  writeFileSync(DASHBOARD, dashboardFile(header + code))
  console.log(`Wrote ${OUT} (${code.length} characters) and ${DASHBOARD}`)
}

if (process.argv[1]?.endsWith('build-cards-rules.ts')) {
  await main()
}
