// Bundles the Last Card rules into ONE file for the Edge Function `cards-game` (PROJECT_PLAN.md §15 step 2), so the
// live game on the server plays by exactly the same rules (and tests) as the solo game in the app.
//
//   npm run build:cards-rules      → supabase/functions/cards-game/rules.js
//
// Run it after changing any file in RULE_SOURCES. The first line of rules.js holds a fingerprint of those files;
// src/lib/cardsRulesBundle.test.ts fails if they changed but rules.js wasn't built again.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { build } from 'rolldown'

export const RULE_SOURCES = ['src/lib/cards.ts', 'src/lib/cardsLive.ts', 'src/lib/board.ts', 'src/lib/quiz.ts']
const OUT = 'supabase/functions/cards-game/rules.js'

/** Same text on Windows and elsewhere (git may turn line endings into CRLF on checkout). */
export function rulesFingerprint(read: (path: string) => string = (p) => readFileSync(p, 'utf8')): string {
  const hash = createHash('sha256')
  for (const path of RULE_SOURCES) hash.update(`${path}\n${read(path).replace(/\r\n/g, '\n')}\n`)
  return hash.digest('hex').slice(0, 16)
}

async function main() {
  const result = await build({ input: 'src/lib/cardsLive.ts', write: false, output: { format: 'esm' } })
  const code = result.output[0].code
  const header = [
    `// rules-fingerprint: ${rulesFingerprint()}`,
    '// GENERATED by scripts/build-cards-rules.ts from src/lib/cardsLive.ts (and cards.ts, board.ts, quiz.ts).',
    '// Do not edit by hand: change those files, then run `npm run build:cards-rules`.',
    '',
  ].join('\n')
  writeFileSync(OUT, header + code)
  console.log(`Wrote ${OUT} (${code.length} characters)`)
}

if (import.meta.url === `file://${process.argv[1]?.replace(/\\/g, '/').replace(/^([A-Za-z]):/, '/$1:')}` || process.argv[1]?.endsWith('build-cards-rules.ts')) {
  await main()
}
