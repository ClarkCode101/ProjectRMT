// Turns seed question JSON (PROJECT_PLAN.md §4) into SQL you can paste into the
// Supabase SQL Editor. Built-in questions have owner_id = NULL, which RLS blocks
// from the app, so seeding goes through SQL instead of a service-role key.
//
// This file is also used by scripts/build-seed-sql.ts (run by Node directly),
// so it must not use the "@/" import alias.

export const SUBJECT_CODES = ['CC', 'MICRO', 'HEMA', 'BBIS', 'CM', 'HTMLE'] as const
export type SubjectCode = (typeof SUBJECT_CODES)[number]

export type SeedQuestion = {
  subject: SubjectCode
  topic: string
  stem: string
  choices: string[]
  correct_index: number
  explanation?: string
  /** one short note per choice, same order as choices (migration 0008); '' = no note for that choice */
  choice_notes?: string[]
  difficulty?: number
}

/** Checks one parsed JSON value and returns a list of problems (empty = valid). */
export function validateSeedQuestion(value: unknown): string[] {
  const errors: string[] = []
  if (typeof value !== 'object' || value === null) return ['not an object']
  const q = value as Record<string, unknown>

  if (!SUBJECT_CODES.includes(q.subject as SubjectCode)) {
    errors.push(`subject must be one of ${SUBJECT_CODES.join(', ')}`)
  }
  if (typeof q.topic !== 'string' || q.topic.trim() === '') errors.push('topic is required')
  if (typeof q.stem !== 'string' || q.stem.trim() === '') errors.push('stem is required')
  if (
    !Array.isArray(q.choices) ||
    q.choices.length !== 4 ||
    !q.choices.every((c) => typeof c === 'string' && c.trim() !== '')
  ) {
    errors.push('choices must be 4 non-empty strings')
  }
  if (!Number.isInteger(q.correct_index) || (q.correct_index as number) < 0 || (q.correct_index as number) > 3) {
    errors.push('correct_index must be 0, 1, 2 or 3')
  }
  if (q.explanation !== undefined && typeof q.explanation !== 'string') {
    errors.push('explanation must be text')
  }
  if (
    q.choice_notes !== undefined &&
    (!Array.isArray(q.choice_notes) ||
      q.choice_notes.length !== 4 ||
      !q.choice_notes.every((n) => typeof n === 'string'))
  ) {
    errors.push('choice_notes must be 4 strings, one per choice')
  }
  if (
    q.difficulty !== undefined &&
    (!Number.isInteger(q.difficulty) || (q.difficulty as number) < 1 || (q.difficulty as number) > 3)
  ) {
    errors.push('difficulty must be 1, 2 or 3')
  }
  return errors
}

/** Wraps text as a SQL string literal: O'Brien -> 'O''Brien' */
export function sqlString(text: string): string {
  return `'${text.replace(/'/g, "''")}'`
}

// Same normalization the database uses for stem_hash (see 0001_init.sql).
const NORMALIZED_STEM_SQL = (stemLiteral: string) =>
  `md5(trim(regexp_replace(regexp_replace(lower(${stemLiteral}), '[^a-z0-9 ]', ' ', 'g'), '\\s+', ' ', 'g')))`

/**
 * Builds SQL that inserts each question as built-in + verified (the built-in set is fact-checked, with a reference in each explanation).
 * Missing topics are created. Questions whose stem already exists as built-in
 * are skipped, so running the file twice does not create duplicates.
 * Choice notes are also filled into built-in questions that are already in the database, but only
 * when they have no notes yet and their choices are still the same (so a choice she edited never
 * gets a note written for the old wording).
 */
export function questionsToSql(questions: SeedQuestion[]): string {
  const lines: string[] = [
    '-- Generated by scripts/build-seed-sql.ts. Do not edit by hand;',
    '-- edit supabase/seed/questions/*.json and re-run `npm run seed:sql`.',
    'begin;',
    '',
  ]

  const topicKeys = new Set<string>()
  for (const q of questions) {
    const key = `${q.subject}|${q.topic}`
    if (topicKeys.has(key)) continue
    topicKeys.add(key)
    lines.push(
      `insert into topics (subject_id, name) select id, ${sqlString(q.topic)} from subjects where code = ${sqlString(q.subject)} on conflict (subject_id, name) do nothing;`,
    )
  }
  lines.push('')

  for (const q of questions) {
    const stem = sqlString(q.stem)
    const choices = `${sqlString(JSON.stringify(q.choices))}::jsonb`
    const notes = q.choice_notes ? `${sqlString(JSON.stringify(q.choice_notes))}::jsonb` : 'null'
    lines.push(
      [
        'insert into questions (owner_id, topic_id, source, stem, choices, correct_index, explanation, choice_notes, difficulty, status)',
        `select null, t.id, 'builtin', ${stem}, ${choices}, ${q.correct_index}, ${q.explanation ? sqlString(q.explanation) : 'null'}, ${notes}, ${q.difficulty ?? 2}, 'verified'`,
        'from topics t join subjects s on s.id = t.subject_id',
        `where s.code = ${sqlString(q.subject)} and t.name = ${sqlString(q.topic)}`,
        `  and not exists (select 1 from questions x where x.owner_id is null and x.stem_hash = ${NORMALIZED_STEM_SQL(stem)});`,
      ].join('\n'),
    )
    if (q.choice_notes) {
      lines.push(
        [
          `update questions set choice_notes = ${notes}`,
          `where owner_id is null and choice_notes is null and choices = ${choices} and stem_hash = ${NORMALIZED_STEM_SQL(stem)};`,
        ].join('\n'),
      )
    }
  }

  lines.push('', 'commit;', '')
  return lines.join('\n')
}
